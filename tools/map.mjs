// Writes MAP.md: every src file with its line count and the functions, classes and methods in it.
// node tools/map.mjs   (run after moving code; the build order is in tools/files.json)
import fs from 'node:fs';
import path from 'node:path';

const files = [];
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : e.name.endsWith('.js') && files.push(path.join(d, e.name))));
walk('src');
const out = ['# Source map', '', 'Generated by `node tools/map.mjs`. One line per file: lines, then what is defined in it.', ''];
let dir = '';
for (const f of files.sort()) {
  const d = path.dirname(f);
  if (d !== dir) out.push('', `## ${(dir = d)}`, '');
  const L = fs.readFileSync(f, 'utf8').split('\n');
  const names = [];
  let cls = null;
  for (const l of L) {
    let m;
    if ((m = l.match(/^(?:module\.exports = )?class (\w+)/))) names.push((cls = m[1]));
    else if ((m = l.match(/^Object\.assign\((\w+)\.prototype/))) cls = m[1];
    else if ((m = l.match(/^(?:async )?function (\w+)/))) names.push(`${m[1]}()`);
    else if ((m = l.match(/^const ([A-Z_][A-Z0-9_]+) =/))) names.push(m[1]);
    else if (cls && (m = l.match(/^  (?:static |get |set )?(?:async )?(\w+)\(.*\) \{$/)) && m[1] !== 'constructor') names.push(`${cls}.${m[1]}`);
  }
  out.push(`- \`${path.basename(f)}\` (${L.length}): ${names.join(', ') || '—'}`);
}
fs.writeFileSync('MAP.md', out.join('\n') + '\n');
console.log(`MAP.md: ${files.length} files`);
